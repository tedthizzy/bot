"""rover_contracts -- the single source of truth every rover component imports.

Nine modules, one job each:

``units``          the boundary between the model's integers and SI
``ids``            ULIDs for ``cmd_id`` and ``turn_id``, bus session ids
``serial_codec``   the Pi<->MCU line protocol of ARCHITECTURE 5.1
``config``         ``config/robot.toml`` with its compiled ceilings (A33)
``messages``       every message on the robotd bus, frames.sock and brain.sock
``observations``   the vision schemas that cannot carry a skill (A13)
``worldstate``     what the model sees, never raw sensors
``skills``         the skill catalog of ARCHITECTURE 6, as data
``jsonl``          append-only logs and episodes (A34)

Nothing here talks to a device, a socket or a clock.
"""

